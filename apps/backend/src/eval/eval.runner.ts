/**
 * The Phase 5 evaluation runner (plan §2, Obj 6): runs the 20
 * scenarios through the template baseline and the reasoning model,
 * verifies every explanation with the production guardrail, and
 * measures the four metrics.
 *
 * The runner NEVER fabricates a model result. When no LLM client is
 * supplied (no API key), the live system is recorded as 'pending-key'
 * and no model call is attempted — the run still completes, with the
 * baseline fully measured and the mock path exercising the mechanics.
 * A run without a key exits successfully: the missing key is a
 * documented status, not an error.
 *
 * What each system is:
 * - baseline: the production template (readinessTemplate), verified.
 * - llm: the reasoning model via the production prompt construction
 *   (buildReadinessExplanationMessages) and the production guardrail.
 * - mock-correct / mock-corrupt: the fixture client (see
 *   eval.mock-provider.ts), run through the SAME code path as the llm
 *   system, so the mechanics check is real.
 */

export type EvalSystemName =
  'baseline' | 'llm' | 'mock-correct' | 'mock-corrupt';

export type EvalRunStatus = 'ok' | 'parse-error' | 'provider-error' | 'refused';

/**
 * What the report stores per run: the verdict, the counts, and the
 * FAILING checks only. Passing check rows are not stored — a 19-scenario
 * run produces ~1,300 of them, and they add nothing the counts do not
 * already say. The failures are the evidence; the full rows can be
 * regenerated by re-running the eval (it is deterministic).
 */
export interface SlimVerification {
  passed: boolean;
  checksPassed: number;
  checksFailed: number;
  failures: GuardrailCheckRow[];
}

function slimVerification(result: GuardrailResult): SlimVerification {
  return {
    passed: result.passed,
    checksPassed: result.checksPassed,
    checksFailed: result.checksFailed,
    failures: result.failures,
  };
}

export interface EvalRun {
  repeat: number;
  status: EvalRunStatus;
  latencyMs: number;
  usage: TokenUsage | null;
  costUsd: number | null;
  /** The parsed answer (null when the run produced none). */
  answer: AiAnswer | null;
  /** The guardrail verdict (a synthetic failure when unparseable). */
  verification: SlimVerification | null;
  conclusions: AnswerConclusions | null;
  error: string | null;
}

export interface EvalSystemResult {
  system: EvalSystemName;
  status: 'measured' | 'pending-key' | 'not-run';
  runs: EvalRun[];
  grounding: GroundingSummary | null;
  /** Pairwise agreement across repeats (null with < 2 runs). */
  consistency: number | null;
  latency: LatencySummary | null;
  /** Total USD cost across runs (null when usage was not reported). */
  totalCostUsd: number | null;
  /** First run's answer, for the rating pack (null when none). */
  answer: AiAnswer | null;
}

export interface EvalScenarioResult {
  scenarioId: string;
  name: string;
  archetype: string;
  /** 'unavailable' when the formula could not score the scenario. */
  status: 'measured' | 'unavailable';
  score: number | null;
  band: string | null;
  maxScore: number | null;
  /** The assessment, stored so the rating pack can show the context. */
  assessment: ReadinessAssessment | null;
  /** Measured size of the prompt the model would receive, in chars. */
  promptChars: number;
  baseline: EvalSystemResult | null;
  llm: EvalSystemResult;
  mockCorrect: EvalSystemResult | null;
  mockCorrupt: EvalSystemResult | null;
}

export interface EvalReport {
  generatedAt: string;
  models: {
    primary: string;
    reasoning: string;
    embeddings: string;
  };
  pricesAsOf: string;
  keyPresent: boolean;
  repeats: number;
  scenariosTotal: number;
  scenariosMeasured: number;
  scenariosUnavailable: number;
  scenarios: EvalScenarioResult[];
  /** Aggregate grounding per system across measured scenarios. */
  grounding: Record<EvalSystemName, GroundingSummary | null>;
  /** Mean self-consistency per system (null when unmeasured). */
  consistency: Record<EvalSystemName, number | null>;
  /** Total measured USD cost per system (null when unmeasured). */
  totalCostUsd: Record<EvalSystemName, number | null>;
  /** Total measured prompt characters across measured scenarios. */
  totalPromptChars: number;
  /** What is still waiting on the API key (human-readable). */
  pending: string[];
}

export interface EvalRunnerOptions {
  /** The live client, or null when no API key exists. */
  client: LlmClient | null;
  /** Self-consistency repeats per scenario (default 5, plan §2). */
  repeats?: number;
  /** Which mock modes to run (default: both when no key, none with). */
  mock?: MockMode[];
  /** Run only these scenario ids (default: all 20). */
  scenarioIds?: string[];
  /** Progress callback: (done, total, scenarioId). */
  onProgress?: (done: number, total: number, scenarioId: string) => void;
}

function syntheticFailure(detail: string): SlimVerification {
  const row = {
    claimIndex: -1,
    claimText: '',
    sourceTool: '',
    checkType: 'source' as const,
    expected: null,
    actual: null,
    passed: false,
    detail,
  };
  return {
    passed: false,
    checksPassed: 0,
    checksFailed: 1,
    failures: [row],
  };
}

function emptySystemResult(
  system: EvalSystemName,
  status: EvalSystemResult['status'],
): EvalSystemResult {
  return {
    system,
    status,
    runs: [],
    grounding: null,
    consistency: null,
    latency: null,
    totalCostUsd: null,
    answer: null,
  };
}

function sleep(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

/**
 * Whether a provider failure is worth retrying: timeouts, rate limits
 * (429) and server errors (5xx) are transient; other 4xx (bad key, no
 * credit, unknown model) will fail the same way every time, so the run
 * fails fast instead of burning retries. Unknown (non-provider) errors
 * are client bugs, not transient failures — also fail fast.
 */
function isRetryableProviderError(error: unknown): boolean {
  if (!(error instanceof LlmProviderError)) return false;
  if (error.timedOut) return true;
  if (error.status === 429) return true;
  if (error.status !== undefined && error.status >= 500) return true;
  return false;
}

/**
 * The provider error message with its HTTP status attached, when the
 * provider gave one. The first live run (24 Nov 2026) recorded bare
 * "The AI provider returned an error." 54 times with no way to tell a
 * 429 from a 500 — the status is the diagnosis.
 */
function providerErrorMessage(error: unknown): string {
  const message =
    error instanceof Error ? error.message : 'Unknown provider error.';
  if (error instanceof LlmProviderError) {
    if (error.timedOut) return `${message} (timed out)`;
    if (error.status !== undefined) return `${message} (HTTP ${error.status})`;
  }
  return message;
}

/**
 * Sum token usage across the calls of one repeat (a parse retry spends
 * tokens twice; the run's cost must reflect both calls).
 */
function addUsage(
  a: TokenUsage | null,
  b: TokenUsage | null,
): TokenUsage | null {
  if (a === null) return b;
  if (b === null) return a;
  return {
    promptTokens: a.promptTokens + b.promptTokens,
    completionTokens: a.completionTokens + b.completionTokens,
    totalTokens: a.totalTokens + b.totalTokens,
  };
}

async function runModelSystem(
  system: EvalSystemName,
  client: LlmClient,
  model: string,
  assessment: ReadinessAssessment,
  question: string,
  repeats: number,
): Promise<EvalSystemResult> {
  // The structured-output instructions are part of the prompt: the first
  // live run (24 Nov 2026) never told the model the required shape, and
  // 41/95 replies came back as valid JSON missing the claims array.
  // Production's structuredAnswer appends the same instructions.
  const messages: ChatMessage[] = [
    ...buildReadinessExplanationMessages(
      assessment,
      question,
      READINESS_EXPLANATION_MAX_DATA_CHARS,
    ),
    { role: 'user', content: STRUCTURED_OUTPUT_INSTRUCTIONS },
  ];
  const price = priceForModel(model);
  const runs: EvalRun[] = [];
  for (let repeat = 1; repeat <= repeats; repeat++) {
    const started = performance.now();
    // Pacing between live-system repeats only (mocks are fixtures; the
    // live system fires ~100 real calls per run and hit rate limits).
    const pace = async (): Promise<void> => {
      if (system === 'llm' && repeat < repeats) {
        await sleep(EVAL_REPEAT_PACE_MS);
      }
    };
    // Provider call with retry on transient failures (24 Nov 2026:
    // instant rejections clustered late in the run — rate limiting, not
    // bad input). Non-retryable failures fail fast.
    let completion: ChatCompletion | null = null;
    let providerError: unknown = null;
    for (let attempt = 0; attempt <= EVAL_PROVIDER_MAX_RETRIES; attempt++) {
      try {
        completion = await client.chat({
          model,
          messages,
          responseFormatJson: true,
          maxTokens: EVAL_REASONING_MAX_TOKENS,
          timeoutMs: EVAL_TIMEOUT_MS,
        });
        providerError = null;
        break;
      } catch (error) {
        providerError = error;
        if (
          attempt < EVAL_PROVIDER_MAX_RETRIES &&
          isRetryableProviderError(error)
        ) {
          await sleep(EVAL_PROVIDER_RETRY_BASE_MS * 2 ** attempt);
          continue;
        }
        break;
      }
    }
    if (completion === null) {
      const message = providerErrorMessage(providerError);
      runs.push({
        repeat,
        status: 'provider-error',
        latencyMs: performance.now() - started,
        usage: null,
        costUsd: null,
        answer: null,
        verification: syntheticFailure(`The model call failed: ${message}`),
        conclusions: null,
        error: message,
      });
      await pace();
      continue;
    }
    // One parse retry with a correction prompt, mirroring production's
    // structuredAnswer: the malformed reply is shown back to the model
    // with the required shape restated. A failed retry keeps the
    // original parse error.
    let parsed = parseStructuredJson(completion.content, AiAnswerSchema);
    let totalUsage = completion.usage;
    if (!parsed.ok) {
      try {
        const retry = await client.chat({
          model,
          messages: [
            ...messages,
            { role: 'assistant', content: completion.content },
            {
              role: 'user',
              content: correctionPrompt(completion.content ?? ''),
            },
          ],
          responseFormatJson: true,
          maxTokens: EVAL_REASONING_MAX_TOKENS,
          timeoutMs: EVAL_TIMEOUT_MS,
        });
        const reparsed = parseStructuredJson(retry.content, AiAnswerSchema);
        totalUsage = addUsage(totalUsage, retry.usage);
        if (reparsed.ok) parsed = reparsed;
      } catch {
        // The retry itself failed; the original parse error stands.
      }
    }
    // Latency covers the whole repeat, retries included.
    const latencyMs = performance.now() - started;
    const costUsd = price ? costOfUsage(totalUsage, price) : null;
    if (!parsed.ok) {
      runs.push({
        repeat,
        status: 'parse-error',
        latencyMs,
        usage: totalUsage,
        costUsd,
        answer: null,
        verification: syntheticFailure(
          `The model reply could not be parsed as a structured answer: ${parsed.error}`,
        ),
        conclusions: null,
        error: parsed.error,
      });
      await pace();
      continue;
    }
    const answer = parsed.value;
    if (answer.refused) {
      runs.push({
        repeat,
        status: 'refused',
        latencyMs,
        usage: totalUsage,
        costUsd,
        answer,
        // A refusal is verified as vacuous by the guardrail
        // (verifyAnswer passes refusals with zero checks).
        verification: slimVerification(
          verifyAnswer(
            answer,
            buildReadinessGuardrailContext(
              `eval-${system}-${repeat}`,
              'eval',
              assessment,
            ),
          ),
        ),
        conclusions: extractConclusions(answer),
        error: null,
      });
      await pace();
      continue;
    }
    const verification = slimVerification(
      verifyAnswer(
        answer,
        buildReadinessGuardrailContext(
          `eval-${system}-${repeat}`,
          'eval',
          assessment,
        ),
      ),
    );
    runs.push({
      repeat,
      status: 'ok',
      latencyMs,
      usage: totalUsage,
      costUsd,
      answer,
      verification,
      conclusions: extractConclusions(answer),
      error: null,
    });
    await pace();
  }
  const verifications = runs
    .map((run) => run.verification)
    .filter((result): result is SlimVerification => result !== null);
  const conclusions = runs
    .map((run) => run.conclusions)
    .filter((value): value is AnswerConclusions => value !== null);
  const costs = runs
    .map((run) => run.costUsd)
    .filter((value): value is number => value !== null);
  const anyUsageReported = runs.some((run) => run.usage !== null);
  return {
    system,
    status: 'measured',
    runs,
    grounding:
      verifications.length > 0 ? summarizeGrounding(verifications) : null,
    consistency: pairwiseAgreement(conclusions),
    latency: summarizeLatency(runs.map((run) => run.latencyMs)),
    totalCostUsd: anyUsageReported
      ? costs.reduce((sum, value) => sum + value, 0)
      : null,
    answer: runs[0]?.answer ?? null,
  };
}

function baselineSystemResult(
  assessment: ReadinessAssessment,
): EvalSystemResult {
  const baseline = runBaseline(assessment);
  const run: EvalRun = {
    repeat: 1,
    status: 'ok',
    latencyMs: baseline.latencyMs,
    usage: null,
    costUsd: 0,
    answer: baseline.answer,
    verification: slimVerification(baseline.verification),
    conclusions: extractConclusions(baseline.answer),
    error: null,
  };
  return {
    system: 'baseline',
    status: 'measured',
    runs: [run],
    grounding: summarizeGrounding([baseline.verification]),
    consistency: null,
    latency: summarizeLatency([baseline.latencyMs]),
    totalCostUsd: 0,
    answer: baseline.answer,
  };
}

function aggregateGrounding(
  results: EvalScenarioResult[],
  system: EvalSystemName,
): GroundingSummary | null {
  const verifications: VerificationCounts[] = [];
  for (const result of results) {
    const systemResult =
      system === 'baseline'
        ? result.baseline
        : system === 'llm'
          ? result.llm
          : system === 'mock-correct'
            ? result.mockCorrect
            : result.mockCorrupt;
    if (!systemResult || systemResult.status !== 'measured') continue;
    for (const run of systemResult.runs) {
      if (run.verification) verifications.push(run.verification);
    }
  }
  return verifications.length > 0 ? summarizeGrounding(verifications) : null;
}

function aggregateConsistency(
  results: EvalScenarioResult[],
  system: EvalSystemName,
): number | null {
  const values: number[] = [];
  for (const result of results) {
    const systemResult =
      system === 'baseline'
        ? result.baseline
        : system === 'llm'
          ? result.llm
          : system === 'mock-correct'
            ? result.mockCorrect
            : result.mockCorrupt;
    if (
      systemResult &&
      systemResult.status === 'measured' &&
      systemResult.consistency !== null
    ) {
      values.push(systemResult.consistency);
    }
  }
  if (values.length === 0) return null;
  return values.reduce((sum, value) => sum + value, 0) / values.length;
}

function aggregateCost(
  results: EvalScenarioResult[],
  system: EvalSystemName,
): number | null {
  let total = 0;
  let any = false;
  for (const result of results) {
    const systemResult =
      system === 'baseline'
        ? result.baseline
        : system === 'llm'
          ? result.llm
          : system === 'mock-correct'
            ? result.mockCorrect
            : result.mockCorrupt;
    if (
      systemResult &&
      systemResult.status === 'measured' &&
      systemResult.totalCostUsd !== null
    ) {
      total += systemResult.totalCostUsd;
      any = true;
    }
  }
  return any ? total : null;
}

/**
 * Run the evaluation. The client is null when no API key exists —
 * the live system is then 'pending-key' and the run still completes.
 * The mock defaults to both modes when no key exists (mechanics +
 * sensitivity) and off when a key exists (real calls need no mock).
 */
export async function runEval(options: EvalRunnerOptions): Promise<EvalReport> {
  const repeats = options.repeats ?? EVAL_DEFAULT_REPEATS;
  const mockModes =
    options.mock ?? (options.client === null ? ['correct', 'corrupt'] : []);
  const scenarios =
    options.scenarioIds === undefined
      ? EVAL_SCENARIOS
      : EVAL_SCENARIOS.filter((scenario) =>
          options.scenarioIds?.includes(scenario.id),
        );
  const results: EvalScenarioResult[] = [];
  let done = 0;
  for (const scenario of scenarios) {
    const assessment = scoreReadiness(scenario.inputs);
    const promptChars =
      assessment.available === true
        ? JSON.stringify(
            buildReadinessExplanationMessages(
              assessment,
              scenario.question,
              READINESS_EXPLANATION_MAX_DATA_CHARS,
            ),
          ).length
        : 0;
    if (assessment.available !== true) {
      results.push({
        scenarioId: scenario.id,
        name: scenario.name,
        archetype: scenario.archetype,
        status: 'unavailable',
        score: null,
        band: null,
        maxScore: null,
        assessment: null,
        promptChars,
        baseline: null,
        llm: emptySystemResult('llm', 'not-run'),
        mockCorrect: null,
        mockCorrupt: null,
      });
      done += 1;
      options.onProgress?.(done, scenarios.length, scenario.id);
      continue;
    }
    const baseline = baselineSystemResult(assessment);
    const llm =
      options.client === null
        ? emptySystemResult('llm', 'pending-key')
        : await runModelSystem(
            'llm',
            options.client,
            EVAL_REASONING_MODEL,
            assessment,
            scenario.question,
            repeats,
          );
    const mockCorrect = mockModes.includes('correct')
      ? await runModelSystem(
          'mock-correct',
          new MockLlmClient('correct', assessment),
          'mock/correct',
          assessment,
          scenario.question,
          1,
        )
      : null;
    const mockCorrupt = mockModes.includes('corrupt')
      ? await runModelSystem(
          'mock-corrupt',
          new MockLlmClient('corrupt', assessment),
          'mock/corrupt',
          assessment,
          scenario.question,
          1,
        )
      : null;
    results.push({
      scenarioId: scenario.id,
      name: scenario.name,
      archetype: scenario.archetype,
      status: 'measured',
      score: assessment.score,
      band: assessment.band,
      maxScore: assessment.maxScore,
      assessment,
      promptChars,
      baseline,
      llm,
      mockCorrect,
      mockCorrupt,
    });
    done += 1;
    options.onProgress?.(done, scenarios.length, scenario.id);
  }
  const measured = results.filter((result) => result.status === 'measured');
  const pending: string[] = [];
  if (options.client === null) {
    pending.push(
      'Live LLM metrics (grounding, self-consistency, latency, cost) — no OPENROUTER_API_KEY. Re-run with the key set.',
    );
    pending.push(
      'Explanation-quality ratings — the rating pack holds baseline outputs only until the live run adds LLM outputs.',
    );
  }
  return {
    generatedAt: new Date().toISOString(),
    models: {
      primary: EVAL_PRIMARY_MODEL,
      reasoning: EVAL_REASONING_MODEL,
      embeddings: EVAL_EMBEDDING_MODEL,
    },
    pricesAsOf: EVAL_PRICES_AS_OF,
    keyPresent: options.client !== null,
    repeats,
    scenariosTotal: results.length,
    scenariosMeasured: measured.length,
    scenariosUnavailable: results.length - measured.length,
    scenarios: results,
    grounding: {
      baseline: aggregateGrounding(results, 'baseline'),
      llm: aggregateGrounding(results, 'llm'),
      'mock-correct': aggregateGrounding(results, 'mock-correct'),
      'mock-corrupt': aggregateGrounding(results, 'mock-corrupt'),
    },
    consistency: {
      baseline: aggregateConsistency(results, 'baseline'),
      llm: aggregateConsistency(results, 'llm'),
      'mock-correct': aggregateConsistency(results, 'mock-correct'),
      'mock-corrupt': aggregateConsistency(results, 'mock-corrupt'),
    },
    totalCostUsd: {
      baseline: aggregateCost(results, 'baseline'),
      llm: aggregateCost(results, 'llm'),
      'mock-correct': aggregateCost(results, 'mock-correct'),
      'mock-corrupt': aggregateCost(results, 'mock-corrupt'),
    },
    totalPromptChars: results.reduce(
      (sum, result) => sum + result.promptChars,
      0,
    ),
    pending,
  };
}

/** Format a rate as a percentage with 1 decimal, or '—' when null. */
function pct(rate: number | null): string {
  return rate === null ? '—' : `${(rate * 100).toFixed(1)}%`;
}

function usd(value: number | null): string {
  return value === null ? '—' : `$${value.toFixed(4)}`;
}

/**
 * Render the report as the human-readable results table (the Phase 5
 * deliverable table). Pending systems show 'pending key', never a
 * number — the table must be quotable in the report as it stands.
 */
export function renderReportMarkdown(report: EvalReport): string {
  const lines: string[] = [];
  lines.push('# FinVerse AI — Phase 5 Evaluation Results');
  lines.push('');
  lines.push(`Generated: ${report.generatedAt}`);
  lines.push(
    `Models (pinned): primary ${report.models.primary}; reasoning ${report.models.reasoning}; embeddings ${report.models.embeddings}.`,
  );
  lines.push(`Prices as of: ${report.pricesAsOf}.`);
  lines.push(
    `API key present: ${report.keyPresent ? 'yes' : 'no'}. Self-consistency repeats: ${report.repeats}.`,
  );
  lines.push(
    `Scenarios: ${report.scenariosTotal} total, ${report.scenariosMeasured} measured, ${report.scenariosUnavailable} unavailable (no score measurable).`,
  );
  lines.push('');
  lines.push('## Aggregate metrics');
  lines.push('');
  lines.push(
    '| System | Grounding (answers) | Grounding (checks) | Self-consistency | Total cost |',
  );
  lines.push('| --- | --- | --- | --- | --- |');
  const row = (system: EvalSystemName, label: string): string => {
    const grounding = report.grounding[system];
    const consistency = report.consistency[system];
    const cost = report.totalCostUsd[system];
    // A null is only 'pending key' for the live system when the key was
    // actually missing. When the key was present but no run succeeded
    // (the 24 Nov 2026 live run: 0/95 parseable), the honest label is
    // 'no successful runs' — 'pending key' would hide a real failure.
    // The baseline and the mocks run without a key, so their nulls mean
    // something else: the baseline is deterministic (no consistency to
    // measure), the mocks run once (no pairs to agree), and neither
    // spends tokens.
    const notRun =
      system === 'llm'
        ? report.keyPresent
          ? 'no successful runs'
          : 'pending key'
        : 'not run';
    const answers =
      grounding === null
        ? notRun
        : `${pct(grounding.answerRate)} (${grounding.answersPassed}/${grounding.answersTotal})`;
    const checks =
      grounding === null
        ? notRun
        : `${pct(grounding.checkRate)} (${grounding.checksPassed}/${grounding.checksTotal})`;
    const consistencyText =
      consistency === null
        ? system === 'baseline'
          ? 'n/a (deterministic)'
          : system === 'llm'
            ? notRun
            : 'n/a (1 run)'
        : pct(consistency);
    const costText =
      cost === null
        ? system === 'llm'
          ? notRun
          : 'n/a (no tokens)'
        : cost === 0
          ? '$0 (no model calls)'
          : usd(cost);
    return `| ${label} | ${answers} | ${checks} | ${consistencyText} | ${costText} |`;
  };
  lines.push(row('baseline', 'Template baseline'));
  lines.push(row('llm', 'LLM (reasoning model)'));
  lines.push(row('mock-correct', 'Mock — correct (fixture)'));
  lines.push(row('mock-corrupt', 'Mock — corrupt (fixture)'));
  lines.push('');
  lines.push(
    'Mock rows exercise the runner mechanics only; they are not model measurements.',
  );
  lines.push('');
  lines.push('## Per-scenario results');
  lines.push('');
  lines.push(
    '| Scenario | Score | Band | Baseline grounding | LLM grounding | LLM consistency | LLM cost |',
  );
  lines.push('| --- | --- | --- | --- | --- | --- | --- |');
  for (const scenario of report.scenarios) {
    const baseline =
      scenario.baseline?.grounding === null ||
      scenario.baseline?.grounding === undefined
        ? scenario.status === 'unavailable'
          ? 'n/a (no score)'
          : '—'
        : pct(scenario.baseline.grounding.answerRate);
    const llmGrounding =
      scenario.llm.status === 'pending-key'
        ? 'pending key'
        : scenario.llm.status === 'not-run'
          ? 'n/a (no score)'
          : pct(scenario.llm.grounding?.answerRate ?? null);
    const llmConsistency =
      scenario.llm.status === 'pending-key'
        ? 'pending key'
        : scenario.llm.status === 'not-run'
          ? 'n/a (no score)'
          : pct(scenario.llm.consistency);
    const llmCost =
      scenario.llm.status === 'pending-key'
        ? 'pending key'
        : scenario.llm.status === 'not-run'
          ? 'n/a (no score)'
          : usd(scenario.llm.totalCostUsd);
    lines.push(
      `| ${scenario.name} (${scenario.scenarioId}) | ${scenario.score ?? '—'} | ${scenario.band ?? '—'} | ${baseline} | ${llmGrounding} | ${llmConsistency} | ${llmCost} |`,
    );
  }
  lines.push('');
  if (report.pending.length > 0) {
    lines.push('## Pending');
    lines.push('');
    for (const item of report.pending) lines.push(`- ${item}`);
    lines.push('');
  }
  lines.push(
    `Total prompt size across measured scenarios: ${report.totalPromptChars.toLocaleString('en-IN')} characters.`,
  );
  lines.push('');
  return lines.join('\n');
}
